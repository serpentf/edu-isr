#!/usr/bin/env node
// Builds a MySQL seed script that creates a course in an empty database (local
// development). It also verifies every challenge and copies course images into
// frontend/public, so deploy/scripts/build.sh runs it as a check.
// To create or update a course on a server with students, use
// backend/scripts/update-course.js: it keeps lesson ids and student progress.
// Targets the tables created by Sequelize sync (underscored, lowercase), not docker/mysql/init.sql.
// Usage: node scripts/build-course-seed.js <course-dir> [output.sql]

const fs = require('fs');
const path = require('path');
const { ROOT, readCourse, resolveLessonLinks, validateChallenges, copyAssets } = require('./lib/course-source');

const courseDir = path.resolve(process.argv[2] || '');
if (!process.argv[2] || !fs.existsSync(path.join(courseDir, 'course.json'))) {
  console.error('Usage: node scripts/build-course-seed.js <course-dir> [output.sql]');
  process.exit(1);
}

const sql = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? '1' : '0';
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
};

const main = async () => {
  const course = readCourse(courseDir);
  const { meta } = course;
  const outFile = path.resolve(process.argv[3] || path.join(ROOT, 'docker/mysql', `seed-${meta.slug}.sql`));

  const lines = [
    `-- Generated by scripts/build-course-seed.js from ${path.relative(ROOT, courseDir)}. Do not edit by hand.`,
    '-- Requires at least one user with role = admin (becomes the course author).',
    'SET NAMES utf8mb4;',
    'START TRANSACTION;',
    '',
    "SET @author_id = (SELECT id FROM `users` WHERE role = 'admin' ORDER BY id LIMIT 1);",
    'INSERT INTO `courses` (`title`, `description`, `slug`, `level`, `duration_hours`, `is_published`, `created_by`, `created_at`, `updated_at`) VALUES',
    `(${[meta.title, meta.description, meta.slug, meta.level, meta.duration_hours, meta.is_published].map(sql).join(', ')}, @author_id, NOW(), NOW());`,
    'SET @course_id = LAST_INSERT_ID();'
  ];

  // Lesson ids are assigned by the database on insert, so links between lessons become
  // placeholders that are replaced with real ids once every lesson is inserted
  const indexOf = new Map(course.lessons.map((lesson, i) => [lesson, i + 1]));
  const placeholder = (lesson) => `__LESSON_${indexOf.get(lesson)}__`;
  const referenced = new Set();

  for (const module of course.modules) {
    lines.push('', `-- ${module.dirName}`);
    lines.push('INSERT INTO `modules` (`course_id`, `title`, `description`, `order_index`, `source_key`, `created_at`, `updated_at`) VALUES');
    lines.push(`(@course_id, ${[module.title, module.description, module.order_index, module.key].map(sql).join(', ')}, NOW(), NOW());`);
    lines.push('SET @module_id = LAST_INSERT_ID();');

    for (const lesson of module.lessons) {
      const content = resolveLessonLinks(course, lesson, (linked) => {
        referenced.add(linked);
        return `/lesson/${placeholder(linked)}`;
      });
      const values = [
        lesson.title,
        content,
        lesson.type,
        lesson.quiz_data ? JSON.stringify(lesson.quiz_data) : null,
        lesson.code_challenge_data ? JSON.stringify(lesson.code_challenge_data) : null,
        lesson.order_index,
        true,
        lesson.key
      ].map(sql);
      lines.push('INSERT INTO `lessons` (`module_id`, `title`, `content`, `type`, `quiz_data`, `code_challenge_data`, `order_index`, `is_published`, `source_key`, `created_at`, `updated_at`) VALUES');
      lines.push(`(@module_id, ${values.join(', ')}, NOW(), NOW());`);
      lines.push(`SET @lesson_${indexOf.get(lesson)} = LAST_INSERT_ID();`);
    }
  }

  if (referenced.size) {
    lines.push('', '-- Links between lessons: placeholders become real lesson ids');
    for (const lesson of referenced) {
      lines.push('UPDATE `lessons` l JOIN `modules` m ON m.id = l.module_id ' +
        `SET l.content = REPLACE(l.content, ${sql(placeholder(lesson))}, @lesson_${indexOf.get(lesson)}) WHERE m.course_id = @course_id;`);
    }
  }
  lines.push('', 'COMMIT;', '');

  await validateChallenges(course);
  fs.writeFileSync(outFile, lines.join('\n'));
  copyAssets(course);

  const count = (predicate) => course.lessons.filter(predicate).length;
  const language = (l) => l.code_challenge_data?.language;
  console.log(`${path.relative(ROOT, outFile)}: ${course.modules.length} modules, ` +
    `${count((l) => l.type === 'text')} text, ${count((l) => l.type === 'code_challenge')} code challenges ` +
    `(${count((l) => language(l) === 'javascript')} auto-graded, ${count((l) => language(l) === 'devtools-lab')} DevTools labs), ` +
    `${count((l) => l.type === 'quiz')} quizzes`);
};

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
